def tag_rus(tag: str) -> str:
    """Расшифровка тега Penn Treebank по-русски (лр. №3)."""
    return TAG_MAP.get(tag, f"Неизвестно ({tag})")


def dep_rus(dep: str) -> str:
    """Расшифровка синтаксической роли по-русски (лр. №3)."""
    return DEP_MAP.get((dep or "").lower(), f"Неизвестно ({dep})")


def pos_rus(pos: str) -> str:
    """Расшифровка универсальной части речи по-русски (лр. №1)."""
    return POS_MAP.get((pos or "").upper(), f"Неизвестно ({pos})")
